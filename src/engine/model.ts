import { wilson, type Proportion } from './metrics';
import { BASELINE_VISITS, MAX_FOLLOWUP_VISITS, calculateChange, calibrationFor } from './scoring';
import { L, type AssessmentLanguage, type Education, type Localised } from './types';

/**
 * Shadow-mode change model.
 *
 * What it is: an L2-regularised logistic regression on a personal trajectory.
 * Features come from all of a person's comparable visits (level, change from
 * their own baseline, slope across every visit, visit-to-visit variability)
 * plus schooling, age band and reported daily-function change. Small and fully
 * explainable: every weight is shown on the Validation page.
 *
 * What keeps it safe:
 * - Trained on one synthetic cohort and evaluated on a second, separately seeded one.
 * - Pre-registered gates. If any gate fails, the model is withheld everywhere.
 * - Shadow mode. It never changes the proposed path, the queue or a referral.
 *   Clinicians see it beside the formula, and disagreements are for audit.
 * - It abstains outside what it was trained on: languages with no calibration,
 *   fewer than four comparable visits, or feature values outside the training range.
 *
 * What it is not: evidence of clinical performance. The cohorts are generated by
 * this prototype's own assumptions, so the evaluation shows the harness works.
 */

export const MODEL_VERSION = 'dhakira-shadow-lr 1.0.0';
export const TRAIN_SEED = 1101;
export const TRAIN_SIZE = 1500;
export const TEST_SEED = 3307;
export const TEST_SIZE = 1500;
export const LAMBDA = 1;
/** The operating point is chosen on training data to keep false referrals down. */
export const TARGET_SPECIFICITY = 0.9;

export const FEATURES: { key: string; label: Localised }[] = [
  { key: 'baseline', label: L('Baseline average', 'متوسط خط الأساس', 'Rata-rata baseline') },
  { key: 'change', label: L('Change from own baseline', 'التغيّر عن خط الأساس الخاص', 'Perubahan dari baseline sendiri') },
  { key: 'slope', label: L('Slope across all visits', 'الميل عبر كل الزيارات', 'Kemiringan di semua kunjungan') },
  { key: 'variability', label: L('Visit-to-visit variability', 'التباين بين الزيارات', 'Variasi antarkunjungan') },
  { key: 'lastDrop', label: L('Latest visit against baseline', 'آخر زيارة مقابل خط الأساس', 'Kunjungan terakhir dibanding baseline') },
  { key: 'eduLow', label: L('Primary schooling or less', 'تعليم ابتدائي أو أقل', 'Pendidikan SD atau kurang') },
  { key: 'eduHigh', label: L('Tertiary schooling', 'تعليم جامعي', 'Pendidikan tinggi') },
  { key: 'age60', label: L('Age 60 to 69', 'العمر 60 إلى 69', 'Usia 60 sampai 69') },
  { key: 'age70', label: L('Age 70 or over', 'العمر 70 فأكثر', 'Usia 70 ke atas') },
  { key: 'function', label: L('Daily-function change reported', 'أُبلغ عن تغيّر في الوظيفة اليومية', 'Perubahan fungsi harian dilaporkan') },
];

export interface ModelInput {
  scores: number[];
  language: AssessmentLanguage;
  education: Education;
  ageBand: AgeBand;
  functionReported: boolean;
}

const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;

/** Raw features, or null when the input is outside what the model covers. */
export function featuresOf(x: ModelInput): number[] | null {
  if (x.scores.length < BASELINE_VISITS + 1) return null;
  if (!calibrationFor(x.language, x.education)) return null;
  const s = x.scores;
  const base = s.slice(0, BASELINE_VISITS);
  const follow = s.slice(BASELINE_VISITS).slice(-MAX_FOLLOWUP_VISITS);
  const bm = mean(base);
  const n = s.length;
  const tMean = (n - 1) / 2;
  let sxy = 0, sxx = 0;
  s.forEach((v, i) => { sxy += (i - tMean) * (v - bm); sxx += (i - tMean) ** 2; });
  const slope = sxy / sxx;
  const diffs = s.slice(1).map((v, i) => v - s[i]);
  const variability = Math.sqrt(mean(diffs.map((d) => d * d)));
  return [
    bm,
    mean(follow) - bm,
    slope,
    variability,
    s[n - 1] - bm,
    x.education === 'low' ? 1 : 0,
    x.education === 'high' ? 1 : 0,
    x.ageBand === '60-69' ? 1 : 0,
    x.ageBand === '70+' ? 1 : 0,
    x.functionReported ? 1 : 0,
  ];
}

export interface TrainedModel {
  version: string;
  weights: number[];
  intercept: number;
  means: number[];
  sds: number[];
  /** Training range per feature, for the out-of-range check. */
  min: number[];
  max: number[];
  threshold: number;
  trainedOn: { seed: number; size: number; rows: number; positives: number };
}

const sigmoid = (z: number) => 1 / (1 + Math.exp(-z));

/** Solves A x = b by Gaussian elimination with partial pivoting. A is small (11 x 11). */
function solve(A: number[][], b: number[]): number[] {
  const n = b.length;
  const M = A.map((row, i) => [...row, b[i]]);
  for (let c = 0; c < n; c += 1) {
    let p = c;
    for (let r = c + 1; r < n; r += 1) if (Math.abs(M[r][c]) > Math.abs(M[p][c])) p = r;
    [M[c], M[p]] = [M[p], M[c]];
    for (let r = c + 1; r < n; r += 1) {
      const f = M[r][c] / M[c][c];
      for (let k = c; k <= n; k += 1) M[r][k] -= f * M[c][k];
    }
  }
  const x = new Array<number>(n).fill(0);
  for (let r = n - 1; r >= 0; r -= 1) {
    let s = M[r][n];
    for (let k = r + 1; k < n; k += 1) s -= M[r][k] * x[k];
    x[r] = s / M[r][r];
  }
  return x;
}

export interface Row { x: number[]; y: number; rec: CohortRecord; visits: number }

/**
 * Each complete record gives two rows, its first four visits and all five, so the
 * model sees both lengths it will meet in practice. Uncalibrated languages are
 * left out, because the model abstains for them.
 */
export function rowsOf(records: CohortRecord[]): Row[] {
  const rows: Row[] = [];
  for (const rec of records) {
    if (!rec.complete || !rec.scores || rec.referenceChange === null) continue;
    for (const visits of [BASELINE_VISITS + 1, rec.scores.length]) {
      const x = featuresOf({ scores: rec.scores.slice(0, visits), language: rec.language, education: rec.education, ageBand: rec.ageBand, functionReported: rec.functionReported });
      if (x) rows.push({ x, y: rec.referenceChange ? 1 : 0, rec, visits });
    }
  }
  return rows;
}

/** Newton-Raphson on the penalised log-likelihood. Deterministic: same data, same weights. */
export function train(records: CohortRecord[], lambda = LAMBDA, meta = { seed: TRAIN_SEED, size: TRAIN_SIZE }): TrainedModel {
  const rows = rowsOf(records);
  const k = FEATURES.length;
  const means = Array.from({ length: k }, (_, j) => mean(rows.map((r) => r.x[j])));
  const sds = Array.from({ length: k }, (_, j) => Math.sqrt(mean(rows.map((r) => (r.x[j] - means[j]) ** 2))) || 1);
  const Z = rows.map((r) => [1, ...r.x.map((v, j) => (v - means[j]) / sds[j])]);
  let beta = new Array<number>(k + 1).fill(0);
  for (let it = 0; it < 50; it += 1) {
    const grad = new Array<number>(k + 1).fill(0);
    const H = Array.from({ length: k + 1 }, () => new Array<number>(k + 1).fill(0));
    Z.forEach((z, i) => {
      const p = sigmoid(z.reduce((s, v, j) => s + v * beta[j], 0));
      const w = p * (1 - p);
      for (let a = 0; a <= k; a += 1) {
        grad[a] += (rows[i].y - p) * z[a];
        for (let b = 0; b <= k; b += 1) H[a][b] += w * z[a] * z[b];
      }
    });
    // The intercept is not penalised.
    for (let a = 1; a <= k; a += 1) { grad[a] -= lambda * beta[a]; H[a][a] += lambda; }
    const step = solve(H, grad);
    beta = beta.map((v, j) => v + step[j]);
    if (Math.max(...step.map(Math.abs)) < 1e-10) break;
  }
  const model: TrainedModel = {
    version: MODEL_VERSION,
    intercept: beta[0],
    weights: beta.slice(1),
    means, sds,
    min: Array.from({ length: k }, (_, j) => Math.min(...rows.map((r) => r.x[j]))),
    max: Array.from({ length: k }, (_, j) => Math.max(...rows.map((r) => r.x[j]))),
    threshold: 0.5,
    trainedOn: { ...meta, rows: rows.length, positives: rows.filter((r) => r.y === 1).length },
  };
  model.threshold = chooseThreshold(rows.map((r) => [score(model, r.x), r.y]));
  return model;
}

export const score = (m: TrainedModel, x: number[]) =>
  sigmoid(m.intercept + x.reduce((s, v, j) => s + m.weights[j] * ((v - m.means[j]) / m.sds[j]), 0));

/** The lowest probability cut that still keeps training specificity at or above the target. */
function chooseThreshold(scored: [number, number][]): number {
  const neg = scored.filter(([, y]) => y === 0).map(([p]) => p).sort((a, b) => a - b);
  const idx = Math.min(neg.length - 1, Math.ceil(TARGET_SPECIFICITY * neg.length) - 1);
  return Number((neg[idx] + 1e-9).toFixed(4));
}

export type Prediction =
  | { ok: true; p: number; above: boolean; threshold: number; contributions: { key: string; label: Localised; value: number }[] }
  | { ok: false; reason: Localised };

export function predict(m: TrainedModel, input: ModelInput): Prediction {
  if (input.scores.length < BASELINE_VISITS + 1) {
    return { ok: false, reason: L('The model needs at least four comparable visits.', 'يحتاج النموذج إلى أربع زيارات قابلة للمقارنة على الأقل.', 'Model memerlukan minimal empat kunjungan yang sebanding.') };
  }
  const x = featuresOf(input);
  if (!x) {
    return { ok: false, reason: L('The model abstains: there is no calibration for this language and schooling group, so it was never trained on it.', 'يمتنع النموذج: لا توجد معايرة لهذه المجموعة من اللغة والتعليم، لذا لم يُدرَّب عليها.', 'Model abstain: kelompok bahasa dan pendidikan ini belum punya kalibrasi, jadi model tidak pernah dilatih untuknya.') };
  }
  const outside = x.findIndex((v, j) => v < m.min[j] - 1e-9 || v > m.max[j] + 1e-9);
  if (outside >= 0) {
    return { ok: false, reason: L(
      `The model abstains: "${FEATURES[outside].label.en}" is outside the range it was trained on.`,
      `يمتنع النموذج: "${FEATURES[outside].label.ar}" خارج النطاق الذي دُرّب عليه.`,
      `Model abstain: "${FEATURES[outside].label.id}" di luar rentang data latihnya.`,
    ) };
  }
  const p = score(m, x);
  const contributions = x.map((v, j) => ({ key: FEATURES[j].key, label: FEATURES[j].label, value: m.weights[j] * ((v - m.means[j]) / m.sds[j]) }))
    .sort((a, b) => Math.abs(b.value) - Math.abs(a.value));
  return { ok: true, p, above: p >= m.threshold, threshold: m.threshold, contributions };
}

/* ----------------------------- Evaluation ----------------------------- */

function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * The same AUC as metrics.auc (Mann-Whitney, ties as half), computed from ranks in
 * O(n log n) so a bootstrap of a few thousand rows stays fast in the browser.
 */
export function aucByRank(positives: number[], negatives: number[]): number | null {
  const np = positives.length, nn = negatives.length;
  if (!np || !nn) return null;
  const all = [...positives.map((v) => [v, 1] as const), ...negatives.map((v) => [v, 0] as const)].sort((a, b) => a[0] - b[0]);
  let rankSum = 0;
  for (let i = 0; i < all.length;) {
    let j = i;
    while (j + 1 < all.length && all[j + 1][0] === all[i][0]) j += 1;
    const avg = (i + j) / 2 + 1;
    for (let k = i; k <= j; k += 1) if (all[k][1] === 1) rankSum += avg;
    i = j + 1;
  }
  return (rankSum - (np * (np + 1)) / 2) / (np * nn);
}

/** Percentile bootstrap over people (not rows), seeded so the interval is reproducible. */
function bootstrapAuc(rows: { p: number; y: number; id: string }[], reps = 300, seed = 77): [number, number] | null {
  const ids = [...new Set(rows.map((r) => r.id))];
  const byId = new Map<string, { p: number; y: number }[]>();
  rows.forEach((r) => byId.set(r.id, [...(byId.get(r.id) ?? []), r]));
  const rand = mulberry32(seed);
  const vals: number[] = [];
  for (let b = 0; b < reps; b += 1) {
    const pos: number[] = [], neg: number[] = [];
    for (let i = 0; i < ids.length; i += 1) {
      for (const r of byId.get(ids[Math.floor(rand() * ids.length)]) ?? []) (r.y ? pos : neg).push(r.p);
    }
    const a = aucByRank(pos, neg);
    if (a !== null) vals.push(a);
  }
  if (!vals.length) return null;
  vals.sort((a, b) => a - b);
  return [vals[Math.floor(0.025 * vals.length)], vals[Math.ceil(0.975 * vals.length) - 1]];
}

export interface Subgroup { group: string; label: string; n: number; positives: number; auc: number | null; sensitivity: Proportion; specificity: Proportion }
export interface CalibrationBin { lo: number; hi: number; predicted: number; observed: Proportion }
export interface Gate { key: string; label: Localised; value: string; pass: boolean }

export interface ModelEvaluation {
  rows: number;
  people: number;
  prevalence: number;
  auc: number | null;
  aucCi: [number, number] | null;
  brier: number;
  brierReference: number;
  sensitivity: Proportion;
  specificity: Proportion;
  falseReferral: Proportion;
  formula: { auc: number | null; sensitivity: Proportion; specificity: Proportion; falseReferral: Proportion };
  calibration: CalibrationBin[];
  subgroups: Subgroup[];
  gates: Gate[];
  passed: boolean;
}

export function evaluate(m: TrainedModel, records: CohortRecord[]): ModelEvaluation {
  const rows = rowsOf(records);
  const scored = rows.map((r) => ({ p: score(m, r.x), y: r.y, id: r.rec.id, r }));
  const pos = scored.filter((s) => s.y === 1).map((s) => s.p);
  const neg = scored.filter((s) => s.y === 0).map((s) => s.p);
  const count = (pred: (s: typeof scored[number]) => boolean) => {
    let tp = 0, fp = 0, fn = 0, tn = 0;
    for (const s of scored) {
      const yes = pred(s);
      if (yes && s.y) tp += 1; else if (yes) fp += 1; else if (s.y) fn += 1; else tn += 1;
    }
    return { sensitivity: wilson(tp, tp + fn), specificity: wilson(tn, tn + fp), falseReferral: wilson(fp, tp + fp) };
  };
  const modelCounts = count((s) => s.p >= m.threshold);

  // The current formula on exactly the same rows: z at or below -1.96, or reported function change.
  const formulaZ = scored.map((s) => {
    const cal = calibrationFor(s.r.rec.language, s.r.rec.education);
    const ch = cal ? calculateChange((s.r.rec.scores as number[]).slice(0, s.r.visits), cal) : null;
    return ch ? ch.z : 0;
  });
  const formulaCounts = count((s) => formulaZ[scored.indexOf(s)] <= -1.96 || s.r.rec.functionReported);
  const formulaAuc = aucByRank(scored.filter((s) => s.y === 1).map((s) => -formulaZ[scored.indexOf(s)]), scored.filter((s) => s.y === 0).map((s) => -formulaZ[scored.indexOf(s)]));

  const prevalence = pos.length / scored.length;
  const brier = mean(scored.map((s) => (s.p - s.y) ** 2));
  const brierReference = prevalence * (1 - prevalence);

  // Five equal-count bins of predicted probability.
  const sorted = [...scored].sort((a, b) => a.p - b.p);
  const calibration: CalibrationBin[] = Array.from({ length: 5 }, (_, b) => {
    const part = sorted.slice(Math.floor((b * sorted.length) / 5), Math.floor(((b + 1) * sorted.length) / 5));
    return { lo: part[0].p, hi: part[part.length - 1].p, predicted: mean(part.map((s) => s.p)), observed: wilson(part.filter((s) => s.y).length, part.length) };
  });

  const groupDefs: { group: string; label: string; test: (r: CohortRecord) => boolean }[] = [
    { group: 'language', label: 'Arabic', test: (r) => r.language === 'ar' },
    { group: 'language', label: 'English', test: (r) => r.language === 'en' },
    { group: 'education', label: 'Primary or less', test: (r) => r.education === 'low' },
    { group: 'education', label: 'Secondary', test: (r) => r.education === 'mid' },
    { group: 'education', label: 'Tertiary', test: (r) => r.education === 'high' },
    { group: 'age', label: '50-59', test: (r) => r.ageBand === '50-59' },
    { group: 'age', label: '60-69', test: (r) => r.ageBand === '60-69' },
    { group: 'age', label: '70+', test: (r) => r.ageBand === '70+' },
  ];
  const subgroups: Subgroup[] = groupDefs.map((g) => {
    const part = scored.filter((s) => g.test(s.r.rec));
    let tp = 0, fp = 0, fn = 0, tn = 0;
    part.forEach((s) => { const yes = s.p >= m.threshold; if (yes && s.y) tp += 1; else if (yes) fp += 1; else if (s.y) fn += 1; else tn += 1; });
    return {
      group: g.group, label: g.label, n: part.length, positives: tp + fn,
      auc: aucByRank(part.filter((s) => s.y).map((s) => s.p), part.filter((s) => !s.y).map((s) => s.p)),
      sensitivity: wilson(tp, tp + fn), specificity: wilson(tn, tn + fp),
    };
  });

  const aucValue = aucByRank(pos, neg);
  const aucCi = bootstrapAuc(scored);
  const worstSubgroupAuc = Math.min(...subgroups.filter((s) => s.positives >= 30).map((s) => s.auc ?? 0));
  const maxCalGap = Math.max(...calibration.map((c) => Math.abs((c.observed.p ?? 0) - c.predicted)));
  const fmt2 = (n: number | null | undefined) => (n === null || n === undefined ? 'n/a' : n.toFixed(3));

  // Pre-registered: written before the first evaluation run and not tuned afterwards.
  const gates: Gate[] = [
    { key: 'auc', label: L('AUC on the held-out cohort, lower 95% bound at least 0.80', 'AUC على المجموعة المحجوزة، الحد الأدنى لفاصل 95% لا يقل عن 0.80', 'AUC pada kohort uji, batas bawah 95% minimal 0.80'), value: `${fmt2(aucValue)} (${fmt2(aucCi?.[0])} to ${fmt2(aucCi?.[1])})`, pass: (aucCi?.[0] ?? 0) >= 0.8 },
    { key: 'formula', label: L('Ranks at least as well as the current formula', 'يرتّب على الأقل بجودة المعادلة الحالية', 'Mengurutkan minimal sebaik rumus saat ini'), value: `${fmt2(aucValue)} vs ${fmt2(formulaAuc)}`, pass: (aucValue ?? 0) >= (formulaAuc ?? 1) },
    { key: 'specificity', label: L('Specificity at the operating point at least 0.85', 'النوعية عند نقطة التشغيل لا تقل عن 0.85', 'Spesifisitas pada titik operasi minimal 0.85'), value: fmt2(modelCounts.specificity.p), pass: (modelCounts.specificity.p ?? 0) >= 0.85 },
    { key: 'calibration', label: L('Calibration: every bin within 0.08 of what was observed', 'المعايرة: كل فئة ضمن 0.08 مما لوحظ', 'Kalibrasi: setiap kelompok dalam 0.08 dari yang teramati'), value: fmt2(maxCalGap), pass: maxCalGap <= 0.08 },
    { key: 'brier', label: L('Brier score better than predicting the base rate', 'درجة Brier أفضل من التنبؤ بالمعدل الأساسي', 'Skor Brier lebih baik daripada menebak angka dasar'), value: `${fmt2(brier)} vs ${fmt2(brierReference)}`, pass: brier < brierReference },
    { key: 'subgroups', label: L('Every language, schooling and age group with 30 or more positives has AUC at least 0.75', 'كل مجموعة لغة وتعليم وعمر فيها 30 حالة إيجابية أو أكثر لها AUC لا يقل عن 0.75', 'Setiap kelompok bahasa, pendidikan, dan usia dengan 30+ kasus positif punya AUC minimal 0.75'), value: fmt2(worstSubgroupAuc), pass: worstSubgroupAuc >= 0.75 },
  ];

  return {
    rows: scored.length,
    people: new Set(scored.map((s) => s.id)).size,
    prevalence,
    auc: aucValue,
    aucCi,
    brier,
    brierReference,
    ...modelCounts,
    formula: { auc: formulaAuc, ...formulaCounts },
    calibration,
    subgroups,
    gates,
    passed: gates.every((g) => g.pass),
  };
}

/** Trains on the training cohort and evaluates on the held-out one. Used to build and check the frozen artifact. */
export function trainAndEvaluate(): ShadowArtifact {
  const model = train(generateCohort(TRAIN_SEED, TRAIN_SIZE));
  return { model, evaluation: evaluate(model, generateCohort(TEST_SEED, TEST_SIZE)) };
}

export interface ShadowArtifact { model: TrainedModel; evaluation: ModelEvaluation }
